const esc=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const SYM={}; SYM_GROUPS.forEach(([,o])=>Object.assign(SYM,o));
function symVal(v){
  if(!v) return '';
  let chip='',rest=v;
  if(v[0]==='?'){chip='<span class="vq">hledáme</span>';rest=v.slice(1).trim()}
  else if(v[0]==='~'){chip='<span class="vc">dopočítáš</span>';rest=v.slice(1).trim()}
  return chip+(rest?`<span class="vv">${esc(rest)}</span>`:'');
}
function symRow(entry,withVal){
  let k,v='',m;
  if(Array.isArray(entry)){[k,v,m]=entry}else{const i=entry.indexOf(':');k=i<0?entry:entry.slice(0,i);v=i<0?'':entry.slice(i+1)}
  const s=SYM[k]; if(!s){console.warn('Chybí značka:',k);return ''}
  return `<div class="sy">\\(${s[0]}\\)</div><div class="sm">${m||s[1]}</div>`+(withVal?`<div class="sv">${symVal(v)}</div>`:'');
}
